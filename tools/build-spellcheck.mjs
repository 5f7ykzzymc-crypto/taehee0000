import { build } from "esbuild";
import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { createHash } from "node:crypto";
await mkdir("vendor/licenses", { recursive: true });
const prefix = "node_modules/";
const wasm = await readFile(prefix + "hunspell-wasm/wasm/hunspell.wasm");
const result = await build({
  entryPoints: ["tools/spellcheck-worker.js"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["safari16.4", "chrome110"],
  write: false,
  minify: true,
  legalComments: "inline",
  external: ["module", "fs", "fs/promises", "path", "url"],
  define: { "import.meta.url": '"file:///yeobaek-embedded-hunspell.js"' },
  plugins: [
    {
      name: "inline-wasm",
      setup(build) {
        build.onResolve({ filter: /^yeobaek:wasm$/ }, () => ({
          path: "wasm",
          namespace: "embedded",
        }));
        build.onLoad({ filter: /.*/, namespace: "embedded" }, () => ({
          contents: "export default " + JSON.stringify(wasm.toString("base64")),
          loader: "js",
        }));
      },
    },
  ],
});
const source = result.outputFiles[0].text;
await writeFile(
  "vendor/hunspell-engine.js",
  "/* Hunspell WebAssembly 0.3.0; see vendor/licenses and THIRD_PARTY_NOTICES.md. Generated by tools/build-spellcheck.mjs. */\nself.YeobaekHunspellWorkerSource=" +
    JSON.stringify(source) +
    ";\n",
);
const dictionary = {
  version: "hunspell-dict-ko 0.7.94",
  license: "GPL-3.0-or-later",
};
const checksums = {};
for (const ext of ["aff", "dic"]) {
  const bytes = await readFile(prefix + "dictionary-ko/index." + ext);
  dictionary[ext] = gzipSync(bytes, { level: 9 }).toString("base64");
  checksums["dictionary-ko/index." + ext] = createHash("sha256")
    .update(bytes)
    .digest("hex");
}
checksums["hunspell-wasm/wasm/hunspell.wasm"] = createHash("sha256")
  .update(wasm)
  .digest("hex");
await writeFile(
  "vendor/korean-dictionary.js",
  "/* Korean dictionary, GPL-3.0-or-later. Copyright hunspell-dict-ko contributors and National Institute of Korean Language; see THIRD_PARTY_NOTICES.md. */\nself.YeobaekKoreanDictionary=" +
    JSON.stringify(dictionary) +
    ";\n",
);
for (const name of [
  "hunspell-wasm-0.3.0-source.tar.gz",
  "hunspell-dict-ko-0.7.94-source.tar.gz",
]) {
  checksums["sources/" + name] = createHash("sha256")
    .update(await readFile("vendor/sources/" + name))
    .digest("hex");
}
await writeFile(
  "vendor/CHECKSUMS.json",
  JSON.stringify(checksums, null, 2) + "\n",
);
for (const name of ["COPYING", "COPYING.LESSER", "COPYING.MPL"])
  await copyFile(
    prefix + "hunspell-wasm/" + name,
    "vendor/licenses/hunspell-" + name,
  );
await copyFile(
  prefix + "dictionary-ko/license",
  "vendor/licenses/korean-dictionary-license.md",
);
console.log(
  "Bundled worker, inline WebAssembly, and gzip-compressed Korean dictionary. No runtime fetches or imports required.",
);
